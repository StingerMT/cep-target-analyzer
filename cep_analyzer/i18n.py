    def t(self, key, *args):
        """Translate a key, optionally formatting with args."""
        text = self._dicts.get(self._lang, {}).get(key, key)
        if args:
            try:
                return text.format(*args)
            except Exception:
                return text
        return text

    @property
    def lang(self):
        return self._lang

    def set_language(self, lang):
        if lang in self._dicts and lang != self._lang:
            self._lang = lang
            self.languageChanged.emit(lang)
    
    def is_rtl(self):
        """Check if current language is right-to-left."""
        return self._lang == "he"
    
    def unit_display(self, unit: str) -> str:
        """Convert unit to localized display format."""
        if self._lang == "he":
            if unit == "cm":
                return 'ס"מ'
            elif unit == "mrad":
                return "אלפיות"
        return unit
